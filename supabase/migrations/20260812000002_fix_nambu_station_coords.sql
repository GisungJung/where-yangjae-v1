-- 남부터미널역 좌표 정정에 따른 region 재분류.
--
-- 20260812000001의 백필이 잘못된 남부터미널역 좌표(37.4765, 127.0048 — 실제로는
-- 방배 방면)를 기준으로 계산되었다. 올바른 남부터미널역(3호선) 좌표는
-- (37.485013, 127.016189) — 사용자 제공.
--
-- 좌표가 있는 모든 행을 올바른 기준으로 재분류한다 (양쪽 방향 모두 갱신 —
-- 이전 백필의 오분류를 양방향으로 교정). 좌표 없는 행은 '양재' 유지.
-- 적용 시점(2026-08-12)에 수동 지역 편집은 없었으므로 전면 재계산이 안전하다.
-- 이후 지역은 등록/수정 폼 입력이 SSOT — 본 재분류는 1회성 교정.
-- ============================================================================

BEGIN;

UPDATE public.restaurants
SET region = CASE
  WHEN (
    power(lat - 37.485013, 2)
      + power((lng - 127.016189) * cos(radians(37.48)), 2)
  ) < (
    power(lat - 37.4842, 2)
      + power((lng - 127.0344) * cos(radians(37.48)), 2)
  )
  THEN '남부터미널'
  ELSE '양재'
END
WHERE lat IS NOT NULL
  AND lng IS NOT NULL;

COMMIT;

