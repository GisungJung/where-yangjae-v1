-- 좌표 보강(20260514120005) 후 양재역 2km 초과 outlier 6건의 lat/lng를 NULL로
-- 되돌린다. Kakao Local API의 fallback 결과가 동명 식당의 다른 지점/지역을
-- 매칭한 케이스로, 잘못된 좌표가 지도에 표시되는 것보다 NULL이 안전.
-- ============================================================================

UPDATE restaurants SET lat = NULL, lng = NULL
WHERE name IN (
  '정성순대',
  '양재옥',
  '야끼토리 나루토 [강남역]',
  '고화갈비살',
  '텍사스데브라질[고터]',
  'August 8 Chicken'
);
